-- Case numbers. An identity column, not SERIAL: Postgres lets anyone with INSERT on the table use
-- an identity's sequence, while a SERIAL sequence would need its own grant to the API's user
-- (infra/sql/grants.sql covers tables only). Existing rows are numbered as the column is added.
ALTER TABLE "cases" ADD COLUMN "number" INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 24101);
CREATE UNIQUE INDEX "cases_number_key" ON "cases"("number");

-- Removing a note marks it; restoring clears the mark.
ALTER TABLE "case_notes" ADD COLUMN "removedAt" TIMESTAMP(3);

-- A rep's quick note needs only a summary.
ALTER TABLE "case_notes" ALTER COLUMN "issue" DROP NOT NULL;
